// Builds the campus directory (src/data/directory.ts) from the official faculty list.
//
// To update the directory:
//   1. Replace  frontend/data/faculty-details.docx  with the new Word file
//      (or pass another path:  npm run directory -- "C:\path\to\file.docx")
//   2. Run      npm run directory
//
// Word file layout: each person is a heading (the name) followed by a paragraph with line breaks:
//   designation / degree / field of study
import AdmZip from 'adm-zip';
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const input = resolve(process.argv[2] ?? 'data/faculty-details.docx');
const output = resolve('src/data/directory.ts');

if (!existsSync(input)) {
  console.error(`Word file not found: ${input}`);
  process.exit(1);
}

// ---- 1. Read the paragraphs of the Word file --------------------------------
const xml = new AdmZip(input).readAsText('word/document.xml');

const decode = (s) =>
  s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");

const paras = xml
  .split('</w:p>')
  .map((p) => {
    const style = /w:pStyle w:val="([^"]+)"/.exec(p)?.[1] ?? '';
    const text = decode(p.replace(/<w:br[^>]*\/>/g, '\u0001').replace(/<w:tab\/>/g, ' ').replace(/<[^>]+>/g, ''));
    return { style, parts: text.split('\u0001').map((s) => s.trim()).filter(Boolean) };
  })
  .filter((p) => p.parts.length);

// ---- 2. Turn them into people ------------------------------------------------
const people = [];
for (let i = 0; i < paras.length; i++) {
  const p = paras[i];
  // A heading with one line is a name (or a section title) when a detail paragraph follows it
  if (!(p.style && p.parts.length === 1 && paras[i + 1] && !paras[i + 1].style)) continue;

  const name = p.parts[0];
  const d = paras[i + 1].parts;
  let role;
  let qualification;
  let field;

  if (d.length === 4) {
    // designation, program-manager role, department, university (no degree line)
    role = `${d[0]} / ${d[1]}`;
    qualification = '';
    field = d[2];
  } else if (d.length === 2) {
    // the field of study sits on the next line of the file
    role = d[0];
    qualification = d[1];
    const next = paras[i + 2];
    field = next && !next.style && next.parts.length === 1 ? next.parts[0] : '';
  } else {
    [role, qualification, field] = [d[0], d[1], d[2] ?? ''];
  }

  // Keep only the degree type (PhD, MS, ME). "MS (Computer Science)" means the brackets hold the field.
  if (qualification) {
    const inner = /\((.*)\)/.exec(qualification)?.[1] ?? '';
    if (!field && inner) field = inner;
    qualification = qualification.split(' (')[0].trim();
  }

  people.push({ name, role, qualification, field });
}

if (people.length === 0) {
  console.error('No people found in the Word file. Check that it follows the expected layout.');
  process.exit(1);
}

// ---- 3. Group, label and write ----------------------------------------------
const isLeader = (p) => /Vice President|Dean|Head of/.test(p.role);
const isManager = (p) => /Program Manager/.test(p.role);
const categoryOf = (p) => (isLeader(p) ? 'Leadership' : isManager(p) ? 'Program Managers' : 'Faculty');

const strip = (n) => n.replace(/^((Prof|Dr|Mr|Ms|Sir)\.?\s+)+/i, '');
const initialsOf = (n) =>
  strip(n)
    .split(/\s+/)
    .filter(Boolean)
    .map((w, i, all) => (i === 0 || i === all.length - 1 ? w[0].toUpperCase() : ''))
    .join('');


// Dummy campus email for every staff member (title removed): two-word names are firstname.lastname, names with
// three or more words use the complete name with dots, e.g. muhammad.danish.khan@szabist.edu.pk.
const usedEmails = new Set();
const emailOf = (n) => {
  const w = strip(n).toLowerCase().replace(/[^a-z\s]/g, '').split(/\s+/).filter(Boolean);
  let email = (w.length >= 3 ? w.join('.') : w[0] + '.' + w[w.length - 1]) + '@szabist.edu.pk';
  if (usedEmails.has(email)) console.warn('Duplicate email: ' + email);
  usedEmails.add(email);
  return email;
};

const usedIds = new Set();
const idOf = (n) => {
  const base = 'fac-' + strip(n).toLowerCase().replace(/[^a-z]+/g, '-').replace(/^-|-$/g, '');
  let id = base;
  for (let k = 2; usedIds.has(id); k++) id = `${base}-${k}`;
  usedIds.add(id);
  return id;
};

const q = (s) => JSON.stringify(s);
const rows = people.map(
  (p) =>
    `  { id: ${q(idOf(p.name))}, name: ${q(p.name)}, role: ${q(p.role)}, qualification: ${q(p.qualification)}, field: ${q(p.field)}, initials: ${q(initialsOf(p.name))}, email: ${q(emailOf(p.name))}, category: ${q(categoryOf(p))} },`,
);

const file = `// Campus directory. GENERATED by "npm run directory" from data/faculty-details.docx. Do not edit by hand:
// change the Word file and run the command again.
// The students at the bottom are sample data until the directory is loaded from the database.
export type DirectoryCategory = 'Leadership' | 'Program Managers' | 'Faculty' | 'Student';

export interface DirectoryContact {
  id: string;
  name: string;
  /** Designation, e.g. "Assistant Professor / Head of Computer Science" */
  role: string;
  /** Degree type only, e.g. "PhD" or "MS" */
  qualification: string;
  /** Area of specialisation, e.g. "Computer Sciences" */
  field: string;
  initials: string;
  /** Dummy campus email, firstname.lastname@szabist.edu.pk. Students have none. */
  email?: string;
  category: DirectoryCategory;
}

export const DIRECTORY_DATA: DirectoryContact[] = [
${rows.join('\n')}
  // Students (sample data)
  { id: 'stu-zainab-fatima', name: 'Zainab Fatima', role: 'Student', qualification: '', field: 'BS Computer Science (Section 8A)', initials: 'ZF', category: 'Student' },
  { id: 'stu-ayesha-khan', name: 'Ayesha Khan', role: 'Student', qualification: '', field: 'BS Computer Science (Section 8A)', initials: 'AK', category: 'Student' },
  { id: 'stu-bilal-tariq', name: 'Bilal Tariq', role: 'Student', qualification: '', field: 'BS Artificial Intelligence (Section 6B)', initials: 'BT', category: 'Student' },
  { id: 'stu-sana-zehra', name: 'Sana Zehra', role: 'Student', qualification: '', field: 'BS Software Engineering (Section 7A)', initials: 'SZ', category: 'Student' },
];
`;

writeFileSync(output, file);

const counts = {};
for (const p of people) counts[categoryOf(p)] = (counts[categoryOf(p)] ?? 0) + 1;
console.log(`Directory updated: ${people.length} people from ${input}`);
for (const [k, v] of Object.entries(counts)) console.log(`  ${k}: ${v}`);
